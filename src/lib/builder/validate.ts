// Inspects generated source. This module never imports child_process and never runs a project.
import type { ProjectFile, ProjectValidation, StackId } from "@/lib/builder/types";

export type { ProjectValidation };

type PackageJson = {
  scripts?: Record<string, unknown>;
  dependencies?: Record<string, unknown>;
  devDependencies?: Record<string, unknown>;
};

type RouteHit = {
  method: string;
  path: string;
  file: string;
  calls: string[];
};

type FetchHit = {
  method: string;
  path: string;
  file: string;
};

const NODE_BUILTINS = new Set([
  "assert",
  "buffer",
  "child_process",
  "crypto",
  "events",
  "fs",
  "http",
  "https",
  "module",
  "net",
  "os",
  "path",
  "process",
  "stream",
  "url",
  "util",
  "zlib",
]);

const LIFECYCLE = ["preinstall", "install", "postinstall", "prepare"];

function stripComments(contents: string): string {
  return contents
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/(^|[^:])\/\/.*$/gm, "$1");
}

function list(items: string[]): string[] {
  return items.length > 0 ? items.map((item) => `- ${item}`) : ["- None."];
}

export function validationReportLines(report: ProjectValidation): string[] {
  return [
    "## Validation report",
    "",
    "Routes, imported functions, and package.json were inspected. This server did not run the project. A feature name in a comment or a string is not an implementation.",
    "",
    "### Files generated by Gemini",
    "",
    ...list(report.geminiFiles),
    "",
    "### Files generated by local templates",
    "",
    ...list(report.templateFiles),
    "",
    "### Requested features implemented",
    "",
    ...list(report.implemented),
    "",
    "### Features missing or incomplete",
    "",
    ...list(report.missing),
    "",
    "### Validation errors",
    "",
    ...list(report.errors),
    "",
  ];
}

function briefOf(input: { objective?: string; functionalRequirements?: string[]; technologies?: string[] }): string {
  return [input.objective ?? "", ...(input.functionalRequirements ?? []), ...(input.technologies ?? [])].join("\n");
}

function asks(text: string, pattern: RegExp): boolean {
  return pattern.test(text);
}

function packageName(specifier: string): string {
  if (specifier.startsWith("@")) {
    const [scope, name] = specifier.split("/");
    return name ? `${scope}/${name}` : specifier;
  }
  return specifier.split("/")[0] ?? specifier;
}

function parsePackage(contents: string): PackageJson | null {
  try {
    const parsed = JSON.parse(contents) as unknown;
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) return null;
    return parsed as PackageJson;
  } catch {
    return null;
  }
}

function nearestPackage(file: string, packages: Map<string, PackageJson | null>): { path: string; json: PackageJson | null } | null {
  const parts = file.split("/");
  for (let index = parts.length - 1; index >= 0; index -= 1) {
    const dir = parts.slice(0, index).join("/");
    const path = dir ? `${dir}/package.json` : "package.json";
    if (packages.has(path)) return { path, json: packages.get(path) ?? null };
  }
  return null;
}

function resolveRelative(from: string, specifier: string, paths: Set<string>): string | null {
  if (!specifier.startsWith(".")) return null;
  const stack = from.split("/").slice(0, -1);
  for (const part of specifier.split("/")) {
    if (!part || part === ".") continue;
    if (part === "..") stack.pop();
    else stack.push(part);
  }
  const target = stack.join("/");
  const candidates = [
    target,
    `${target}.ts`,
    `${target}.tsx`,
    `${target}.js`,
    `${target}.jsx`,
    `${target}.css`,
    `${target}.json`,
    `${target}/index.ts`,
    `${target}/index.tsx`,
    `${target}/index.js`,
  ];
  return candidates.find((candidate) => paths.has(candidate)) ?? null;
}

function exportedNames(contents: string): Set<string> {
  const names = new Set<string>();
  for (const match of contents.matchAll(/export\s+(?:async\s+)?function\s+([A-Za-z0-9_]+)/g)) names.add(match[1]);
  for (const match of contents.matchAll(/export\s+(?:const|let|class|type|interface|enum)\s+([A-Za-z0-9_]+)/g)) {
    names.add(match[1]);
  }
  for (const match of contents.matchAll(/export\s*\{([^}]+)\}/g)) {
    for (const part of match[1].split(",")) {
      const name = part.trim().split(/\s+as\s+/).pop()?.trim();
      if (name && /^[A-Za-z0-9_]+$/.test(name)) names.add(name);
    }
  }
  return names;
}

function namedImports(clause: string): string[] {
  const match = clause.match(/\{([\s\S]*)\}/);
  if (!match) return [];
  return match[1]
    .split(",")
    .map((part) => part.trim())
    .filter((part) => part && !part.startsWith("type "))
    .map((part) => part.replace(/^type\s+/, "").split(/\s+as\s+/).pop()?.trim() ?? "")
    .filter((name) => /^[A-Za-z0-9_]+$/.test(name));
}

function functionBody(contents: string, name: string): string {
  const match = new RegExp(`(?:export\\s+)?(?:async\\s+)?function\\s+${name}\\s*\\(`).exec(contents);
  if (!match || match.index < 0) return "";
  const start = match.index;
  const rest = contents.slice(start + match[0].length);
  const next = rest.search(/\nexport\s/);
  return contents.slice(start, next < 0 ? undefined : start + match[0].length + next);
}

function routesIn(file: string, contents: string): RouteHit[] {
  const code = stripComments(contents);
  const imported = [...code.matchAll(/import\s+([\s\S]*?)\s+from\s+["'](\.[^"']+)["']/g)].flatMap((match) =>
    namedImports(match[1]),
  );
  const hits: RouteHit[] = [];
  const pattern = /\b(?:app|router)\.(get|post|put|patch|delete)\(\s*["'`]([^"'`]+)["'`]/g;
  const marks = [...code.matchAll(pattern)];
  marks.forEach((mark, index) => {
    const start = mark.index ?? 0;
    const end = index + 1 < marks.length ? (marks[index + 1].index ?? code.length) : code.length;
    const slice = code.slice(start, end);
    hits.push({
      method: mark[1].toUpperCase(),
      path: mark[2],
      file,
      calls: imported.filter((name) => new RegExp(`\\b${name}\\s*\\(`).test(slice)),
    });
  });
  if (file.endsWith("/route.ts") || file.endsWith("/route.js")) {
    const api = file.match(/(?:^|\/)app\/api\/(.+)\/route\.[tj]s$/)?.[1] ?? "";
    const path = `/${["api", ...api.split("/")].filter(Boolean).join("/")}`.replace(/\[([^\]]+)\]/g, ":$1");
    for (const method of ["GET", "POST", "PUT", "PATCH", "DELETE"]) {
      if (new RegExp(`export\\s+(?:async\\s+)?function\\s+${method}\\b`).test(code)) {
        hits.push({ method, path, file, calls: imported.filter((name) => new RegExp(`\\b${name}\\s*\\(`).test(code)) });
      }
    }
  }
  return hits;
}

function fetchesIn(file: string, contents: string): FetchHit[] {
  const code = stripComments(contents);
  const hits: FetchHit[] = [];
  for (const match of code.matchAll(/fetch\(\s*(`[^`]*`|"[^"]*"|'[^']*')([\s\S]{0,500}?)\)/g)) {
    const raw = match[1].slice(1, -1).split("?")[0];
    const path = raw.replace(/\$\{[^}]+\}/g, ":param");
    const method = /method\s*:\s*["'](GET|POST|PUT|PATCH|DELETE)["']/i.exec(match[2])?.[1]?.toUpperCase() ?? "GET";
    if (path.startsWith("/")) hits.push({ method, path, file });
  }
  return hits;
}

function normalizePath(path: string): string {
  const bare = path.split("?")[0].replace(/\/+$/, "") || "/";
  return bare.replace(/:([A-Za-z0-9_]+)/g, ":param").replace(/\$\{[^}]+\}/g, ":param");
}

function samePath(left: string, right: string): boolean {
  return normalizePath(left) === normalizePath(right);
}

export function validateProject(input: {
  stack: StackId;
  technologies?: string[];
  objective?: string;
  functionalRequirements?: string[];
  files: ProjectFile[];
}): ProjectValidation {
  const files = input.files.filter((file) => file.path !== "README.md");
  const byPath = new Map(files.map((file) => [file.path, file.contents]));
  const paths = new Set(byPath.keys());
  const errors: string[] = [];
  const implemented: string[] = [];
  const missing: string[] = [];
  const packages = new Map<string, PackageJson | null>();
  for (const [path, contents] of byPath) {
    if (path.endsWith("package.json")) packages.set(path, parsePackage(contents));
  }

  for (const [path, json] of packages) {
    if (!json) {
      errors.push(`${path} is not a JSON object.`);
      continue;
    }
    const scripts = json.scripts ?? {};
    const dev = typeof scripts.dev === "string" && scripts.dev.trim().length > 0;
    const start = typeof scripts.start === "string" && scripts.start.trim().length > 0;
    if (!dev && !start) errors.push(`${path} has no dev or start script.`);
    for (const name of LIFECYCLE) {
      if (typeof scripts[name] === "string") errors.push(`${path} contains a ${name} script. It was not run.`);
    }
  }

  const codeFiles = files.filter((file) => /\.(tsx?|jsx?)$/.test(file.path));
  for (const file of codeFiles) {
    const code = stripComments(file.contents);
    for (const match of code.matchAll(/(?:^|\n)\s*import\s+["']([^"']+)["']/g)) {
      if (!match[1].startsWith(".")) continue;
      if (!resolveRelative(file.path, match[1], paths)) {
        errors.push(`${file.path} imports ${match[1]}, and that file is not in the archive.`);
      }
    }
    for (const match of code.matchAll(/(?:^|\n)\s*import\s+([^;]*?)\s+from\s+["']([^"']+)["']/g)) {
      const specifier = match[2];
      if (specifier.startsWith(".")) {
        const resolved = resolveRelative(file.path, specifier, paths);
        if (!resolved) {
          errors.push(`${file.path} imports ${specifier}, and that file is not in the archive.`);
          continue;
        }
        const names = namedImports(match[1]);
        const exported = exportedNames(byPath.get(resolved) ?? "");
        for (const name of names) {
          if (!exported.has(name)) errors.push(`${file.path} imports ${name} from ${specifier}, and that export is missing.`);
        }
        continue;
      }
      if (specifier.startsWith("node:") || NODE_BUILTINS.has(packageName(specifier))) continue;
      const owner = nearestPackage(file.path, packages);
      const declared = owner?.json
        ? { ...(owner.json.dependencies ?? {}), ...(owner.json.devDependencies ?? {}) }
        : null;
      if (!owner) {
        errors.push(`${file.path} imports ${specifier}, and no package.json covers that file.`);
      } else if (!declared || !(packageName(specifier) in declared)) {
        errors.push(`${file.path} imports ${packageName(specifier)}, and ${owner.path} does not depend on it.`);
      }
    }
  }

  for (const [path, contents] of byPath) {
    if (!path.endsWith(".html")) continue;
    const dir = path.split("/").slice(0, -1).join("/");
    for (const match of contents.matchAll(/<script[^>]*\ssrc=["']([^"']+)["']/g)) {
      const src = match[1].replace(/^\//, "");
      if (src.startsWith("http") || src.startsWith(".")) continue;
      const candidates = dir ? [src, `${dir}/${src}`] : [src];
      if (!candidates.some((candidate) => paths.has(candidate))) {
        errors.push(`${path} references ${src}, and that file is not in the archive.`);
      }
    }
  }

  const routes = codeFiles.flatMap((file) => routesIn(file.path, file.contents));
  const fetches = codeFiles.flatMap((file) => fetchesIn(file.path, file.contents));
  const brief = briefOf(input);
  const wantsApi = input.stack === "express" || input.stack === "fullstack" || asks(brief, /\b(api|endpoint|routes?)\b/i);
  const wantsCrud = input.stack === "express" || input.stack === "fullstack" || asks(brief, /\bcrud\b|\b(update|delete)\b/i);
  const wantsDatabase =
    input.stack === "fullstack" ||
    (input.technologies ?? []).some((item) => /mongo/i.test(item)) ||
    asks(brief, /\bmongo(?:db)?\b/i);
  const wantsClient = input.stack === "fullstack";
  const wantsAuth = asks(brief, /\b(authentication|password|sign-in|signin|login)\b/i);

  const health = routes.find((route) => route.method === "GET" && samePath(route.path, "/health"));
  if (wantsApi && health) implemented.push(`GET /health is registered in ${health.file}.`);
  if (wantsApi && !health && (input.stack === "express" || input.stack === "fullstack")) {
    missing.push("GET /health is not registered.");
  }

  const crud: { label: string; methods: string[]; mongo: RegExp }[] = [
    { label: "list items", methods: ["GET"], mongo: /\.find\s*\(/ },
    { label: "create an item", methods: ["POST"], mongo: /\.insertOne\s*\(/ },
    { label: "update an item", methods: ["PUT", "PATCH"], mongo: /\.(?:updateOne|findOneAndUpdate)\s*\(/ },
    { label: "delete an item", methods: ["DELETE"], mongo: /\.deleteOne\s*\(/ },
  ];

  function storeBody(route: RouteHit): string {
    const contents = byPath.get(route.file) ?? "";
    const code = stripComments(contents);
    const bodies: string[] = [];
    for (const match of code.matchAll(/import\s+([\s\S]*?)\s+from\s+["'](\.[^"']+)["']/g)) {
      const names = namedImports(match[1]).filter((name) => route.calls.includes(name));
      const resolved = resolveRelative(route.file, match[2], paths);
      const target = resolved ? (byPath.get(resolved) ?? "") : "";
      for (const name of names) bodies.push(functionBody(target, name));
    }
    return bodies.join("\n");
  }

  if (wantsCrud) {
    for (const operation of crud) {
      const title = `${operation.label[0].toUpperCase()}${operation.label.slice(1)}`;
      const registered = routes.find(
        (entry) => operation.methods.includes(entry.method) && /\/api\/items/.test(normalizePath(entry.path)),
      );
      const route = registered && registered.calls.length > 0 ? registered : undefined;
      if (!route) {
        missing.push(
          registered
            ? `${registered.method} ${registered.path} is registered and does not call an imported store function.`
            : `${title} has no API route that calls an imported store function.`,
        );
        continue;
      }
      implemented.push(`${route.method} ${route.path} in ${route.file} calls ${route.calls.join(", ")}.`);
      if (wantsDatabase) {
        if (operation.mongo.test(storeBody(route))) implemented.push(`${title} calls a MongoDB driver method.`);
        else missing.push(`${title} does not call a MongoDB operation.`);
      }
    }
  } else if (wantsApi && routes.length === 0) {
    missing.push("API routes were requested and none are registered.");
  }

  if (wantsDatabase && !wantsCrud) {
    missing.push("MongoDB was requested and this project has no item routes that call it.");
  }

  if (wantsClient) {
    for (const operation of crud) {
      const server = routes.find(
        (route) => operation.methods.includes(route.method) && /\/api\/items/.test(normalizePath(route.path)),
      );
      const client = fetches.find(
        (call) =>
          operation.methods.includes(call.method) &&
          server &&
          samePath(call.path, server.path),
      );
      if (server && client) implemented.push(`${client.file} calls ${client.method} ${client.path}.`);
      else missing.push(`The client does not call a matching route to ${operation.label}.`);
    }
    for (const call of fetches) {
      const match = routes.some((route) => route.method === call.method && samePath(route.path, call.path));
      if (!match) errors.push(`${call.file} calls ${call.method} ${call.path}, and no API route matches it.`);
    }
  }

  if (wantsAuth) {
    const code = codeFiles.map((file) => stripComments(file.contents)).join("\n");
    const present =
      /\b(bcrypt|jsonwebtoken|passport|argon2)\b/.test(code) &&
      /\/api\/(?:login|signup|session)/.test(code) &&
      /\bpassword\b/.test(code);
    if (present) implemented.push("An authentication route imports a password library and reads a password.");
    else missing.push("Authentication was requested and no login route imports a password library.");
  }

  for (const requirement of input.functionalRequirements ?? []) {
    const covered = implemented.some((item) => item.toLowerCase().includes(requirement.toLowerCase()));
    if (!covered) missing.push(`Not verified from source: ${requirement}`);
  }

  return {
    geminiFiles: input.files.filter((file) => file.origin === "gemini").map((file) => file.path),
    templateFiles: input.files.filter((file) => file.origin !== "gemini").map((file) => file.path),
    implemented,
    missing,
    errors,
  };
}
